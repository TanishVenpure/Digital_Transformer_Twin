def _assess_risk(transformer_id: str, *, until: str | None = None, until2: str | None = None) -> dict[str, Any]:
    """Compute maintenance risk from the twin2 check sheet at the two timebar cursors.

    Only checks opened up to their own timebar's cursor are considered, a check resolved after that
    cursor counts as open, and each check's age is measured against its own timebar's cursor.
    """
    checks, cur, _, _ = _load(transformer_id, until, until2)
    as_of = max(cur[1], cur[2])
    if not checks:
        return _empty_assessment(transformer_id, as_of)

    faults = [c for c in checks if c.get("signal") in SEVERITY_SCORE]
    if not faults:
        return _empty_assessment(transformer_id, as_of)

    for c in faults:
        c["_opened"] = datetime.fromisoformat(c["opened_at"])
        c["_age_days"] = max(0, (cur[c["timebar"]] - c["_opened"]).total_seconds() / 86400)
        c["_resolved"] = c["status"] == "RESOLVED"

    contributing_factors = []
    factor_scores = {}

    # 1. Severity (weight 30%): max severity with time decay
    max_severity = 0.0
    severity_driver = None
    for c in faults:
        score = SEVERITY_SCORE.get(c["signal"], 0)
        decay = 0.5 ** (c["_age_days"] / DECAY_HALF_LIFE_DAYS)
        if not c["_resolved"] and score >= SEVERITY_SCORE["MAINTENANCE_REQUIRED"]:
            decay = 1.0
        effective = score * decay
        if effective > max_severity:
            max_severity = effective
            severity_driver = c
    factor_scores["severity"] = round(max_severity, 1)
    sev_evidence = []
    if severity_driver:
        sev_evidence.append({
            "check_no": severity_driver["check_no"], "iot_name": severity_driver.get("iot_name"),
            "signal": severity_driver["signal"], "date": severity_driver.get("date"),
            "status": severity_driver.get("status"), "action": severity_driver.get("recommended_action"),
        })
    by_signal = Counter(c["signal"] for c in faults)
    contributing_factors.append({
        "name": "severity", "weight": WEIGHTS["severity"], "available": True,
        "score": factor_scores["severity"],
        "method": "Max signal severity with time decay (no decay for unresolved serious issues)",
        "explanation": f"Severity maps signals to 0–100: WARNING=25, PREDICTED=50, MAINT_REQ=75, CRITICAL=100. "
                       f"Each decays with a {DECAY_HALF_LIFE_DAYS}-day half-life unless unresolved and serious. "
                       f"The highest effective score becomes the factor score.",
        "signal_counts": dict(by_signal.most_common()),
        "evidence": sev_evidence,
    })

    # 2. Recurrence (weight 25%): repeated checks on the same IoT
    by_iot = Counter((c["timebar"], c["iot"]) for c in faults)
    largest_group = max(by_iot.values()) if by_iot else 0
    recurrence_score = min(100.0, 100.0 * max(0, largest_group - 1) / 3)
    factor_scores["recurrence"] = round(recurrence_score, 1)
    iot_names_map = {}
    for c in faults:
        iot_names_map.setdefault((c["timebar"], c["iot"]), c.get("iot_name", c["iot"]))
    iot_breakdown = [{"timebar": key[0], "iot": key[1], "name": iot_names_map[key], "count": cnt}
                     for key, cnt in by_iot.most_common(7)]
    contributing_factors.append({
        "name": "recurrence", "weight": WEIGHTS["recurrence"], "available": True,
        "score": factor_scores["recurrence"],
        "method": "Repeated checks on the same monitor of the same timebar (saturation at 3 repeats)",
        "explanation": f"Counts checks per monitor; largest group has {largest_group} checks. "
                       f"Score = min(100, 100 * (largest-1) / 3). Saturates at 4+ repeats.",
        "iot_breakdown": iot_breakdown,
    })

    # 3. Recency (weight 20%): how recent is the latest fault
    most_recent_age = min(c["_age_days"] for c in faults)
    most_recent_check = min(faults, key=lambda c: c["_age_days"])
    recency_score = round(100.0 * (0.5 ** (most_recent_age / DECAY_HALF_LIFE_DAYS)), 1)
    factor_scores["recency"] = recency_score
    contributing_factors.append({
        "name": "recency", "weight": WEIGHTS["recency"], "available": True,
        "score": factor_scores["recency"],
        "method": f"Time decay from most recent fault check (half-life {DECAY_HALF_LIFE_DAYS} days)",
        "explanation": f"Most recent fault was {most_recent_age:.1f} days ago. "
                       f"Score = 100 * 0.5^(age/{DECAY_HALF_LIFE_DAYS}). "
                       f"A check today scores 100; one year ago scores 50.",
        "evidence": [{"check_no": most_recent_check["check_no"],
                      "iot_name": most_recent_check.get("iot_name"),
                      "signal": most_recent_check["signal"],
                      "date": most_recent_check.get("date"),
                      "age_days": round(most_recent_age, 1)}],
    })

    # 4. Resolution (weight 15%): unresolved checks score higher
    open_faults = [c for c in faults if not c["_resolved"]]
    if faults:
        resolution_score = round(100.0 * len(open_faults) / len(faults), 1)
    else:
        resolution_score = 0.0
    factor_scores["resolution"] = resolution_score
    open_evidence = [{"check_no": c["check_no"], "iot_name": c.get("iot_name"),
                      "signal": c["signal"], "date": c.get("date"),
                      "action": c.get("recommended_action")}
                     for c in sorted(open_faults, key=lambda c: SEVERITY_SCORE.get(c["signal"], 0), reverse=True)[:5]]
    contributing_factors.append({
        "name": "resolution", "weight": WEIGHTS["resolution"], "available": True,
        "score": factor_scores["resolution"],
        "method": "Fraction of fault checks still unresolved",
        "explanation": f"{len(open_faults)} of {len(faults)} fault checks are unresolved "
                       f"({resolution_score:.1f}%).",
        "open_count": len(open_faults), "total_count": len(faults),
        "evidence": open_evidence,
    })

    # 5. Frequency trend (weight 10%): compare recent vs prior window
    trend_available = False
    trend_score = 0.0
    trend_explanation = ""
    if len(faults) >= 4:
        recent = [c for c in faults if c["_age_days"] <= 365]
        prior = [c for c in faults if 365 < c["_age_days"] <= 730]
        if prior:
            trend_score = min(100.0, 50.0 * len(recent) / len(prior))
            trend_available = True
            trend_explanation = (f"{len(recent)} checks in the last 365 days vs "
                                f"{len(prior)} in the prior 365 days. "
                                f"Score = min(100, 50 * recent/prior).")
        elif recent:
            trend_score = 100.0
            trend_available = True
            trend_explanation = (f"All {len(recent)} checks fall within the last 365 days "
                                f"with no prior-window baseline — scores 100 (all recent).")
    factor_scores["frequency_trend"] = round(trend_score, 1) if trend_available else None
    contributing_factors.append({
        "name": "frequency_trend", "weight": WEIGHTS["frequency_trend"],
        "available": trend_available,
        "score": factor_scores["frequency_trend"],
        "method": "Fault check count in last 365 days vs prior 365 days (requires >= 4 checks)",
        "explanation": trend_explanation or None,
        "unavailable_reason": None if trend_available else "Fewer than 4 fault checks or insufficient history span",
    })

    # Weighted index
    total_weight = sum(WEIGHTS[f["name"]] for f in contributing_factors if f["available"])
    if total_weight < 60:
        return _empty_assessment(transformer_id, as_of, checks_considered=len(checks), faults_considered=len(faults))

    index = sum(
        WEIGHTS[f["name"]] * (f["score"] or 0)
        for f in contributing_factors if f["available"]
    ) / total_weight
    index = round(index, 1)

    # Categorize
    if index >= CATEGORY_HIGH:
        category = "HIGH_MAINTENANCE_RISK"
    elif index >= CATEGORY_MODERATE:
        category = "MODERATE_MAINTENANCE_RISK"
    else:
        category = "LOW_RECORDED_MAINTENANCE_RISK"

    # Escalation: unresolved serious issues
    escalated = False
    review_flags = []
    review_flags.append({"code": "POLICY_NOT_APPROVED", "detail": "Risk policy has not been approved by engineering review."})
    unresolved_serious = [c for c in faults if not c["_resolved"] and SEVERITY_SCORE.get(c["signal"], 0) >= 75]
    if unresolved_serious and category != "HIGH_MAINTENANCE_RISK":
        category = "HIGH_MAINTENANCE_RISK"
        escalated = True
        review_flags.append({
            "code": "UNRESOLVED_SERIOUS_ISSUE",
            "detail": f"{len(unresolved_serious)} unresolved check(s) at MAINTENANCE_REQUIRED or CRITICAL severity.",
        })

    # Trend flags — deduplicate by flag type
    flagged = [c for c in checks if c.get("flag")]
    flag_groups: dict[str, list] = {}
    for c in flagged:
        flag_groups.setdefault(c["flag"], []).append(c)
    for flag_name, occurrences in flag_groups.items():
        dates = sorted(set(c.get("date", "unknown") for c in occurrences))
        iot_names = sorted(set(c.get("iot_name", "unknown") for c in occurrences))
        review_flags.append({
            "code": "TREND_FLAG",
            "flag": flag_name,
            "occurrences": len(occurrences),
            "date_range": f"{dates[0]} to {dates[-1]}" if len(dates) > 1 else dates[0],
            "iot_names": iot_names,
            "detail": (f"Trend flag {flag_name}: {len(occurrences)} occurrence(s) "
                       f"from {dates[0]} to {dates[-1]}, "
                       f"sensors: {', '.join(iot_names)}.") if len(dates) > 1
                      else f"Trend flag {flag_name} raised on {dates[0]}, sensor: {', '.join(iot_names)}.",
        })

    # Data-backed recommendation: highest-severity open check's action
    recommendation = None
    if open_faults:
        top_open = max(open_faults, key=lambda c: SEVERITY_SCORE.get(c["signal"], 0))
        action = top_open.get("recommended_action")
        if action:
            recommendation = {
                "action": action,
                "based_on_check": top_open["check_no"],
                "signal": top_open["signal"],
                "iot_name": top_open.get("iot_name"),
                "date": top_open.get("date"),
                "note": "Based on the highest-severity unresolved maintenance check.",
            }

    # Scoring formula explanation
    weight_parts = [f"{n.replace('_', ' ')} {WEIGHTS[n]}%" for n in WEIGHTS]
    formula_explanation = (
        f"The Maintenance Risk Index is a weighted average of {len(contributing_factors)} factors. "
        "Each factor produces a score from 0 (no concern) to 100 (maximum concern). "
        f"Weights: {', '.join(weight_parts)}. "
        "Final score = sum(weight * score) / sum(weights of available factors). "
        f"Categories: HIGH >= {CATEGORY_HIGH}, MODERATE >= {CATEGORY_MODERATE}, else LOW. "
        "Unresolved MAINTENANCE_REQUIRED or CRITICAL checks force HIGH regardless of score."
    )

    assessment_id = hashlib.sha256(f"{transformer_id}:{cur[1].isoformat()}:{cur[2].isoformat()}".encode()).hexdigest()[:16]

    return {
        "transformer_id": transformer_id,
        "assessment_id": assessment_id,
        "assessed_at": as_of.isoformat(),
        "cursors": {"timebar1": cur[1].isoformat(), "timebar2": cur[2].date().isoformat()},
        "policy_version": POLICY_VERSION,
        "policy_approved": POLICY_APPROVED,
        "maintenance_risk_index": index,
        "risk_category": category,
        "completeness": "COMPLETE",
        "category_escalated": escalated,
        "weight_coverage": round(total_weight, 1),
        "contributing_factors": contributing_factors,
        "review_flags": review_flags,
        "records_considered": len(checks),
        "fault_events_considered": len(faults),
        "history_complete": True,
        "synthetic": True,
        "engineering_review_required": True,
        "methodology_disclaimer": METHODOLOGY_DISCLAIMER,
        "formula_explanation": formula_explanation,
        "recommendation": recommendation,
        "data_source": "twin2 simulated datasets (timebar 1: one day, timebar 2: one year)",
    }


