def _load(transformer_id: str, until: str | None, until2: str | None):
    if transformer_id != twin_sheet.TRANSFORMER_ID:
        raise HTTPException(404, f"No data for transformer {transformer_id}")
    checks, tb1, tb2 = twin_sheet.load_sheet()
    try:
        cur = twin_sheet.cursors(tb1, tb2, until, until2)
    except ValueError:
        raise HTTPException(422, "until must be an ISO-8601 timestamp and until2 an ISO-8601 date")
    return twin_sheet.sheet_at(checks, cur), cur, tb1, tb2


def _value(tb: dict[str, Any], key: str | None, i: int):
    if key is None:   # voltage: the deviation farthest from nominal on either winding
        vals = [tb["series"][k][i] for k in ("v_pri_min", "v_pri_max", "v_sec_min", "v_sec_max")]
        vals = [v for v in vals if v is not None]
        return max(vals, key=abs) if vals else None
    v = tb["series"][key][i]
    if isinstance(v, list):   # per-phase precision deviations
        v = [x for x in v if x is not None]
        return max(v) if v else None
    return v


def _monitor_states(tb1: dict[str, Any], tb2: dict[str, Any], cur: dict[str, Any]) -> list[dict[str, Any]]:
    out = []
    for n, tb, i in ((1, tb1, cur["minute"]), (2, tb2, cur["day"])):
        for mon, key, unit, digits in MONITORS[n]:
            v = _value(tb, key, i)
            out.append({"timebar": n, "monitor": mon, "name": twin_sheet.MONITOR_NAME[(n, mon)],
                        "status": tb["status"][mon][i], "value": None if v is None else round(v, digits), "unit": unit})
    return out


def _chat_context(transformer_id: str, until: str | None = None, until2: str | None = None) -> dict[str, Any]:
    checks, cur, tb1, tb2 = _load(transformer_id, until, until2)
    return {
        "checks": checks,
        "monitors": _monitor_states(tb1, tb2, cur),
        "energized": bool(tb1["series"]["energized"][cur["minute"]]),
        "cursor": {"timebar1": cur[1].isoformat(), "timebar2": cur[2].date().isoformat(),
                   "minute": cur["minute"], "day": cur["day"]},
    }


